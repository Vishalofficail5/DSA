package Arrays;
public class Arrays_Basic {
    public static void main(String[] args) {
        // First method to represent arrays
        int [] x = {1,4,6,32,67,2};
        System.out.println(x[4]);
        // Second method to represent arrays
        int [] arr = new int[5];
        arr[0] = 4;
        arr[1] = 4;
        arr[2] = 6;
        arr[3] = 5;
        arr[4] = 7;
        System.out.print(arr[2]);
    }
}
